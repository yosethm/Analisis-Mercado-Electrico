create table if not exists public.electricity_prices (
  id bigint generated by default as identity primary key,
  codigo_variable text not null,
  fecha date not null,
  codigo_duracion text not null default 'P1D',
  unidad_medida text not null default 'COP/kWh',
  version text not null,
  valor numeric(14, 4) not null,
  created_at timestamptz not null default now(),
  unique (codigo_variable, fecha, version)
);

create index if not exists electricity_prices_fecha_idx
  on public.electricity_prices (fecha desc);

alter table public.electricity_prices enable row level security;

drop policy if exists "Public read access" on public.electricity_prices;
create policy "Public read access"
  on public.electricity_prices for select
  to anon, authenticated
  using (true);

comment on table public.electricity_prices is
  'Precios diarios del mercado eléctrico colombiano provenientes de SIMEM/XM.';

